#!/usr/bin/env python3
"""Convert LuaLS typings (---@class / ---@param / ---@return) into Starlight pages.

Usage:
    python scripts/lua_types_to_starlight.py --resource pmm_skill_system \
        --types <resource>/types/types.lua [--classes <resource>/config.lua ...] \
        --out src/content/docs/skill-system

Writes two pages in --out:
    exports.md  every `function exports.<resource>:Name(...) end`, grouped by the
                section headers (`-- Client-side Exports` between dashed lines)
    types.md    every `---@class` found in --types and --classes

The pages are generated: do not edit them by hand, edit the typings and run again.
"""
import argparse
import re
import sys
from pathlib import Path

OPENERS = {"{": "}", "<": ">", "(": ")", "[": "]"}
CLOSERS = set(OPENERS.values())


def split_type(text):
    """Split 'type rest of the line' where the type may contain spaces inside {} <> ()."""
    text = text.strip()
    depth = 0
    for i, ch in enumerate(text):
        if ch in OPENERS:
            depth += 1
        elif ch in CLOSERS:
            depth -= 1
        elif ch.isspace() and depth == 0:
            return text[:i], text[i:].strip()
    return text, ""


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def code(text):
    return f"`{cell(text)}`" if text else ""


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def is_dashes(line):
    line = line.strip()
    return len(line) > 3 and set(line) == {"-"}


def parse(path, resource):
    """Return (functions, classes) found in a typings file."""
    functions, classes = [], []
    section = None
    desc, params, returns = [], [], []
    cls = None
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    for i, raw in enumerate(lines):
        line = raw.strip()
        if line.startswith("---@class"):
            name = line[len("---@class"):].strip().split(":")[0].strip()
            cls = {"name": name, "desc": " ".join(desc), "fields": []}
            classes.append(cls)
            desc = []
            continue
        if line.startswith("---@field"):
            body = line[len("---@field"):].strip()
            name, _, rest = body.partition(" ")
            ftype, fdesc = split_type(rest)
            optional = name.endswith("?")
            name = name.rstrip("?")
            if ftype.endswith("?"):
                optional = True
                ftype = ftype[:-1]
            if cls is not None:
                cls["fields"].append((name, ftype, optional, fdesc))
            continue
        if line.startswith("---@param"):
            body = line[len("---@param"):].strip()
            name, _, rest = body.partition(" ")
            ptype, pdesc = split_type(rest)
            params.append((name.rstrip("?"), ptype, pdesc))
            continue
        if line.startswith("---@return"):
            body = line[len("---@return"):].strip()
            rtype, rest = split_type(body)
            rname, _, rdesc = rest.partition(" ")
            returns.append((rtype, rname, rdesc.strip()))
            continue
        if line.startswith("---@"):
            continue  # other annotations are not documented
        if line.startswith("---"):
            desc.append(line[3:].strip())
            continue
        if line.startswith("--"):
            # section header: a comment between two dashed lines
            if (
                i > 0 and i + 1 < len(lines)
                and is_dashes(lines[i - 1]) and is_dashes(lines[i + 1])
            ):
                section = line[2:].strip()
            continue
        fm = re.match(rf"^function\s+exports\.{re.escape(resource)}:(\w+)\(([^)]*)\)\s*end$", line)
        if fm:
            functions.append(
                {
                    "section": section,
                    "name": fm.group(1),
                    "args": fm.group(2).strip(),
                    "desc": " ".join(desc),
                    "params": params,
                    "returns": returns,
                }
            )
        desc, params, returns, cls = [], [], [], None
    return functions, classes


def render_exports(resource, functions, title):
    out = [
        "---",
        f"title: {title}",
        f"description: Every export of {resource}, generated from its Lua typings.",
        "sidebar:",
        "  order: 90",
        "---",
        "",
        f"<!-- Generated by scripts/lua_types_to_starlight.py from the typings of {resource}. Do not edit. -->",
        "",
        f"Call them with `exports.{resource}:<Name>(...)`.",
    ]
    last = object()
    for fn in functions:
        if fn["section"] != last:
            last = fn["section"]
            if last:
                out += ["", f"## {last}"]
        out += ["", f"### {fn['name']}", ""]
        if fn["desc"]:
            out += [fn["desc"], ""]
        out += ["```lua", f"exports.{resource}:{fn['name']}({fn['args']})", "```"]
        if fn["params"]:
            out += ["", table(["Parameter", "Type", "Description"],
                              [[code(n), code(t), cell(d)] for n, t, d in fn["params"]])]
        if fn["returns"]:
            out += ["", table(["Returns", "Type", "Description"],
                              [[code(n), code(t), cell(d)] for t, n, d in fn["returns"]])]
    return "\n".join(out) + "\n"


def render_types(resource, classes, title):
    out = [
        "---",
        f"title: {title}",
        f"description: Lua types of {resource}, generated from its typings.",
        "sidebar:",
        "  order: 91",
        "---",
        "",
        f"<!-- Generated by scripts/lua_types_to_starlight.py from the typings of {resource}. Do not edit. -->",
        "",
        "Add the `types/` folder of the resource to your editor's Lua language server library to get these types.",
    ]
    for c in classes:
        out += ["", f"## {c['name']}", ""]
        if c["desc"]:
            out += [c["desc"], ""]
        if c["fields"]:
            out += [table(["Field", "Type", "Required", "Description"],
                          [[code(n), code(t), "no" if opt else "yes", cell(d)]
                           for n, t, opt, d in c["fields"]])]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--resource", required=True, help="resource name, e.g. pmm_skill_system")
    ap.add_argument("--types", required=True, help="typings file with the exports")
    ap.add_argument("--classes", nargs="*", default=[], help="extra files to read ---@class from (e.g. config.lua)")
    ap.add_argument("--out", required=True, help="output folder inside src/content/docs")
    a = ap.parse_args()

    functions, classes = parse(a.types, a.resource)
    seen = {c["name"] for c in classes}
    for extra in a.classes:
        _, more = parse(extra, a.resource)
        classes += [c for c in more if c["name"] not in seen]
        seen |= {c["name"] for c in more}
    if not functions:
        sys.exit(f"no exports found in {a.types}")

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "exports.md").write_text(render_exports(a.resource, functions, "Exports"), encoding="utf-8", newline="\n")
    (out / "types.md").write_text(render_types(a.resource, classes, "Types"), encoding="utf-8", newline="\n")
    print(f"{len(functions)} exports, {len(classes)} classes -> {out}")


if __name__ == "__main__":
    main()
